def _truthy(value: object) -> bool:
    if isinstance(value, (bool, np.bool_)):
        return bool(value)
    if value is None or pd.isna(value):
        return False
    return str(value).strip().lower() in {"1", "true", "yes", "y"}


def _finite_float(value: object) -> float | None:
    try:
        result = float(value)
    except (TypeError, ValueError):
        return None
    return result if np.isfinite(result) else None


def _reduce(values: np.ndarray, method: str, axis: int = 0) -> np.ndarray:
    if method == "median":
        return np.nanmedian(values, axis=axis)
    if method == "mean":
        return np.nanmean(values, axis=axis)
    raise ValueError(f"Unsupported reduction: {method}")


def _channels_tsv_path(edf_path: Path) -> Path:
    suffix = "_ieeg.edf"
    if edf_path.name.lower().endswith(suffix):
        return edf_path.with_name(edf_path.name[: -len(suffix)] + "_channels.tsv")
    return edf_path.with_suffix("").with_name(edf_path.stem + "_channels.tsv")


def _good_ieeg_channel_indices(raw: object, channels_tsv: Path) -> list[int]:
    if not channels_tsv.is_file():
        raise ValueError(f"missing channels.tsv: {channels_tsv}")
    channels = pd.read_csv(channels_tsv, sep="\t")
    if "name" not in channels.columns or "type" not in channels.columns:
        raise ValueError("channels.tsv must contain name and type columns")

    channel_type = channels["type"].fillna("").astype(str).str.upper()
    valid = channel_type.isin({"SEEG", "ECOG", "EEG", "IEEG"})
    if "status" in channels.columns:
        valid &= channels["status"].fillna("good").astype(str).str.lower().ne("bad")
    if "good" in channels.columns:
        valid &= channels["good"].map(_truthy)

    good_names = set(channels.loc[valid, "name"].astype(str))
    indices = [index for index, name in enumerate(raw.ch_names) if name in good_names]
    if not indices:
        raise ValueError("channels.tsv contains no matching good iEEG channels")
    return indices


def _resolve_edf_path(value: object, data_root: Path) -> Path:
    path = Path(str(value)).expanduser()
    if not path.is_absolute():
        path = data_root / path
    return path


def analyze_raw_recording(
    row: pd.Series,
    *,
    data_root: Path,
    window_seconds: float,
    overlap_seconds: float,
    duration_per_recording: float | None,
    channel_reduction: str = "median",
    minimum_sampling_frequency_hz: float = DEFAULT_MINIMUM_SAMPLING_FREQUENCY_HZ,
    require_eligibility_flag: bool = True,
    maximum_frequency_hz: float | None = DEFAULT_MAXIMUM_FREQUENCY_HZ,
    raw_reader: Callable[..., object] = mne.io.read_raw_edf,
    welch_function: Callable[..., tuple[np.ndarray, np.ndarray]] = welch,
) -> RecordingSpectrum:
    """Compute a raw, unfiltered, unresampled recording-level Welch PSD.

    The signal path is deliberately minimal: the EDF is opened lazily, a
    contiguous span of samples is read, and Welch is applied to it. No
    high-pass, low-pass, band-pass, notch, re-reference or resampling step
    exists in this function, and the sampling rate always comes from the EDF
    header of the recording being analysed.

    The three admission rules are parameters rather than constants so that the
    >=1 kHz HUP/UCLA cohort and a lower-rate diagnostic cohort can share this
    one implementation. The defaults reproduce the HUP/UCLA rules exactly.
    """
    site = str(row.get("dataset", "")).strip().lower()
    original_sfreq = _finite_float(row.get("original_sampling_frequency_hz"))
    if site not in ALLOWED_LINE_NOISE_DATASETS:
        raise ValueError(
            "dataset is outside the supported scope "
            f"{list(ALLOWED_LINE_NOISE_DATASETS)}: {site or '<missing>'}"
        )
    if require_eligibility_flag and not _truthy(row.get("eligible_sfreq_ge_1000")):
        raise ValueError("recording is not verified as sampling-frequency eligible")
    if require_eligibility_flag and original_sfreq is None:
        raise ValueError("recording is not verified as sampling-frequency eligible")
    if original_sfreq is not None and original_sfreq < minimum_sampling_frequency_hz:
        raise ValueError(
            f"original sampling frequency is below {minimum_sampling_frequency_hz:g} Hz: "
            f"{original_sfreq:g}"
        )

    edf_path = _resolve_edf_path(row.get("edf_path"), data_root)
    raw = raw_reader(edf_path, preload=False, verbose="ERROR")
    try:
        header_sfreq = float(raw.info["sfreq"])
        if not np.isfinite(header_sfreq) or header_sfreq < minimum_sampling_frequency_hz:
            raise ValueError(
                f"EDF header sampling frequency is below {minimum_sampling_frequency_hz:g} Hz: "
                f"{header_sfreq:g}"
            )
        # The header is the authority. When the inventory also carries a rate the two
        # must agree, so a stale inventory can never silently mislabel a spectrum.
        if original_sfreq is not None and not np.isclose(
            header_sfreq, original_sfreq, rtol=0.0, atol=1e-6
        ):
            raise ValueError(
                "inventory/header sampling-frequency disagreement: "
                f"{original_sfreq:g} versus {header_sfreq:g} Hz"
            )

        picks = _good_ieeg_channel_indices(raw, _channels_tsv_path(edf_path))
        n_per_seg = int(round(window_seconds * header_sfreq))
        n_overlap = int(round(overlap_seconds * header_sfreq))
        if n_per_seg <= 0 or n_overlap < 0 or n_overlap >= n_per_seg:
            raise ValueError("invalid Welch window or overlap")

        available_samples = int(raw.n_times)
        requested_samples = available_samples
        if duration_per_recording is not None:
            requested_samples = min(
                available_samples, int(round(duration_per_recording * header_sfreq))
            )
        if requested_samples < n_per_seg:
            raise ValueError(
                f"recording has fewer than one {window_seconds:g}-second Welch segment"
            )
        start = max(0, (available_samples - requested_samples) // 2)
        stop = start + requested_samples
        data = raw.get_data(picks=picks, start=start, stop=stop)

        frequencies, channel_psd = welch_function(
            data,
            fs=header_sfreq,
            window="hann",
            nperseg=n_per_seg,
            noverlap=n_overlap,
            detrend="constant",
            scaling="density",
            axis=-1,
        )
        resolution = header_sfreq / n_per_seg
        # Never evaluate at or above this recording's own Nyquist frequency. The
        # optional fixed cap can only lower that bound, never raise it.
        nyquist_bound = header_sfreq / 2.0 - resolution
        maximum_frequency = (
            nyquist_bound
            if maximum_frequency_hz is None
            else min(float(maximum_frequency_hz), nyquist_bound)
        )
        frequency_mask = (frequencies >= 0.5) & (frequencies <= maximum_frequency)
        if not frequency_mask.any():
            raise ValueError("no PSD bins fall in the requested frequency range")
        band_limited_psd = channel_psd[:, frequency_mask]
        recording_power = _reduce(band_limited_psd, channel_reduction)
        return RecordingSpectrum(
            site=site,
            participant_id=str(row.get("participant_id", "")),
            recording_index=row.get("recording_index", ""),
            edf_path=str(edf_path),
            frequencies_hz=frequencies[frequency_mask],
            power=recording_power,
            sampling_frequency_hz=header_sfreq,
            number_of_channels=len(picks),
            n_per_seg=n_per_seg,
            n_overlap=n_overlap,
            frequency_resolution_hz=resolution,
            analyzed_duration_seconds=requested_samples / header_sfreq,
            q25_power=np.nanpercentile(band_limited_psd, 25, axis=0),
            q75_power=np.nanpercentile(band_limited_psd, 75, axis=0),
        )
    finally:
        close = getattr(raw, "close", None)
        if callable(close):
            close()


def _common_frequency_grid(
    spectra: Sequence[RecordingSpectrum], window_seconds: float
) -> np.ndarray:
    resolution = 1.0 / window_seconds
    upper = min(float(spectrum.frequencies_hz[-1]) for spectrum in spectra)
    lower_bin = int(np.ceil(0.5 / resolution))
    upper_bin = int(np.floor((upper + resolution * 1e-6) / resolution))
    return np.arange(lower_bin, upper_bin + 1, dtype=float) * resolution


def aggregate_recordings_by_subject_and_site(
    recordings: Sequence[RecordingSpectrum],
    *,
    window_seconds: float,
    recording_reduction: str = "median",
    site_reduction: str = "median",
) -> dict[str, SiteSpectrum]:
    """Aggregate recordings within subjects, then equally weighted subjects."""
    result: dict[str, SiteSpectrum] = {}
    for site in sorted({recording.site for recording in recordings}):
        site_recordings = [recording for recording in recordings if recording.site == site]
        grid = _common_frequency_grid(site_recordings, window_seconds)
        subject_ids = sorted({recording.participant_id for recording in site_recordings})
        subject_curves = []
        for participant_id in subject_ids:
            participant_recordings = [
                recording
                for recording in site_recordings
                if recording.participant_id == participant_id
            ]
            interpolated = np.vstack(
                [
                    np.interp(grid, recording.frequencies_hz, recording.power)
                    for recording in participant_recordings
                ]
            )
            subject_curves.append(_reduce(interpolated, recording_reduction))
        subject_power = np.vstack(subject_curves)
        result[site] = SiteSpectrum(
            site=site,
            frequencies_hz=grid,
            central_power=_reduce(subject_power, site_reduction),
            q25_power=np.nanpercentile(subject_power, 25, axis=0),
            q75_power=np.nanpercentile(subject_power, 75, axis=0),
            subject_power=subject_power,
            participant_ids=subject_ids,
            number_of_recordings=len(site_recordings),
        )
    return result


def compute_line_noise_metrics(
    site_spectra: dict[str, SiteSpectrum],
) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    for site, spectrum in sorted(site_spectra.items()):
        candidates: dict[float, list[str]] = {}
        for family, frequencies in LINE_NOISE_CANDIDATES.items():
            for frequency in frequencies:
                candidates.setdefault(float(frequency), []).append(family)
        for frequency, families in sorted(candidates.items()):
            if frequency > spectrum.frequencies_hz[-1]:
                continue
            distance = np.abs(spectrum.frequencies_hz - frequency)
            background_mask = (
                (distance >= LOCAL_BACKGROUND_INNER_HZ)
                & (distance <= LOCAL_BACKGROUND_OUTER_HZ)
            )
            if not background_mask.any():
                continue
            power = float(np.interp(frequency, spectrum.frequencies_hz, spectrum.central_power))
            background = float(np.nanmedian(spectrum.central_power[background_mask]))
            ratio = power / background if background > 0 else np.nan
            rows.append(
                {
                    "site": site,
                    "candidate_frequency_hz": frequency,
                    "candidate_family": ";".join(families),
                    "power_at_candidate_frequency": power,
                    "local_background_power": background,
                    "peak_to_background_ratio": ratio,
                    "peak_to_background_db": 10.0 * np.log10(ratio) if ratio > 0 else np.nan,
                    "number_of_subjects": len(spectrum.participant_ids),
                    "number_of_recordings": spectrum.number_of_recordings,
                }
            )
    return pd.DataFrame(rows)


def make_review_table(metrics: pd.DataFrame) -> pd.DataFrame:
    review = metrics[
        [
            "site",
            "candidate_frequency_hz",
            "peak_to_background_db",
            "number_of_subjects",
        ]
    ].copy()
    review["automatically_flagged_for_review"] = (
        review["peak_to_background_db"] >= REVIEW_FLAG_THRESHOLD_DB
    )
    review["manually_approved"] = ""
    review["reviewer_comment"] = ""
    return review


def _plot_site_spectrum(spectrum: SiteSpectrum, destination: Path) -> None:
    figure, axis = plt.subplots(figsize=(13, 6))
    axis.fill_between(
        spectrum.frequencies_hz,
        spectrum.q25_power,
        spectrum.q75_power,
        alpha=0.25,
        label="Across-subject IQR",
    )
    axis.plot(
        spectrum.frequencies_hz,
        spectrum.central_power,
        linewidth=1.2,
        label="Site central tendency",
    )
    axis.set_yscale("log")
    axis.set_xlim(0.5, spectrum.frequencies_hz[-1])
    axis.set_xlabel("Frequency (Hz)")
    axis.set_ylabel("Power spectral density")
    axis.set_title(f"Raw unfiltered spectrum: {spectrum.site.upper()}")
    axis.grid(alpha=0.2)
    axis.legend()
    figure.tight_layout()
    figure.savefig(destination, dpi=160)
    plt.close(figure)


def _plot_comparison(site_spectra: dict[str, SiteSpectrum], destination: Path) -> None:
    figure, axis = plt.subplots(figsize=(13, 6))
    for site, spectrum in sorted(site_spectra.items()):
        axis.plot(
            spectrum.frequencies_hz,
            spectrum.central_power,
            linewidth=1.2,
            label=f"{site.upper()} subject central tendency",
        )
    axis.set_yscale("log")
    axis.set_xlim(0.5, min(s.frequencies_hz[-1] for s in site_spectra.values()))
    axis.set_xlabel("Frequency (Hz)")
    axis.set_ylabel("Power spectral density")
    axis.set_title("Raw unfiltered HUP/UCLA spectra")
    axis.grid(alpha=0.2)
    axis.legend()
    figure.tight_layout()
    figure.savefig(destination, dpi=160)
    plt.close(figure)


