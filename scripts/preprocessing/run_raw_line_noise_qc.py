#!/usr/bin/env python3
"""
Describe the spectral content of a small number of Omni-iEEG recordings.

The script:
- selects n recordings per site;
- selects n recordings per dataset;
- computes a descriptive Welch power spectral density (PSD);
- creates individual and grouped figures;
- writes CSV tables and a RESULTS_SUMMARY.md report.


The PSD curves are normalized separately for each recording so that their
spectral shapes can be compared despite amplitude-scale differences.
"""

