BANDS = [
    ("delta_1_4", 1.0, 4.0),
    ("theta_4_8", 4.0, 8.0),
    ("alpha_8_13", 8.0, 13.0),
    ("beta_13_30", 13.0, 30.0),
    ("gamma_30_80", 30.0, 80.0),
    ("high_gamma_80_150", 80.0, 150.0),
]

EXCLUDED_CHANNEL_PATTERN = re.compile(
    r"(ECG|EKG|EMG|EOG|TRIG|TRIGGER|STIM|STATUS|ANNOT)",
    flags=re.IGNORECASE,
)


