def _select_inventory_rows(inventory: pd.DataFrame, args: argparse.Namespace) -> pd.DataFrame:
    required = {
        "recording_index",
        "participant_id",
        "dataset",
        "edf_path",
        "original_sampling_frequency_hz",
        "eligible_sfreq_ge_1000",
    }
    missing = sorted(required - set(inventory.columns))
    if missing:
        raise ValueError(f"inventory is missing columns: {', '.join(missing)}")
    requested = {str(value).lower() for value in args.datasets}
    unsupported = requested - set(HUP_UCLA_LINE_NOISE_DATASETS)
    if unsupported:
        raise ValueError(f"only ucla and hup are supported: {sorted(unsupported)}")
    selected = inventory.copy()
    selected["dataset"] = selected["dataset"].astype(str).str.lower()
    selected = selected[selected["dataset"].isin(requested)]
    selected = selected[selected["eligible_sfreq_ge_1000"].map(_truthy)]
    selected = selected[
        pd.to_numeric(selected["original_sampling_frequency_hz"], errors="coerce") >= 1000.0
    ]
    if args.max_subjects_per_site is not None:
        kept_parts = []
        for _, group in selected.groupby("dataset", sort=True):
            participant_ids = sorted(group["participant_id"].astype(str).unique())[
                : args.max_subjects_per_site
            ]
            kept_parts.append(group[group["participant_id"].astype(str).isin(participant_ids)])
        selected = pd.concat(kept_parts, ignore_index=True) if kept_parts else selected.iloc[0:0]
    selected = selected.sort_values(
        ["dataset", "participant_id", "recording_index"], kind="stable"
    )
    if args.limit is not None:
        selected = selected.head(args.limit)
    return selected.reset_index(drop=True)


def run_line_noise_qc(args: argparse.Namespace) -> None:
    if args.window_seconds <= 0 or args.overlap_seconds < 0:
        raise ValueError("window must be positive and overlap cannot be negative")
    if args.n_jobs < 1:
        raise ValueError("n-jobs must be at least one")
    output_dir = args.output_dir.expanduser()
    output_dir.mkdir(parents=True, exist_ok=True)
    inventory = pd.read_csv(args.inventory_csv.expanduser())
    selected = _select_inventory_rows(inventory, args)
    if selected.empty:
        raise ValueError("no eligible HUP/UCLA recordings remain after selection")

    def process(item: tuple[int, pd.Series]) -> tuple[RecordingSpectrum | None, dict[str, object]]:
        _, row = item
        base = {
            "recording_index": row["recording_index"],
            "participant_id": row["participant_id"],
            "site": row["dataset"],
            "edf_path": row["edf_path"],
        }
        try:
            spectrum = analyze_raw_recording(
                row,
                data_root=args.data_root.expanduser(),
                window_seconds=args.window_seconds,
                overlap_seconds=args.overlap_seconds,
                duration_per_recording=args.duration_per_recording,
                channel_reduction=args.channel_reduction,
            )
            base.update(
                {
                    "contributed": True,
                    "exclusion_reason": "",
                    "sampling_frequency_hz": spectrum.sampling_frequency_hz,
                    "good_ieeg_channels": spectrum.number_of_channels,
                    "analyzed_duration_seconds": spectrum.analyzed_duration_seconds,
                    "n_per_seg": spectrum.n_per_seg,
                    "n_overlap": spectrum.n_overlap,
                    "frequency_resolution_hz": spectrum.frequency_resolution_hz,
                }
            )
            return spectrum, base
        except Exception as error:  # keep an auditable per-recording failure table
            logging.warning("Skipping %s: %s", row["edf_path"], error)
            base.update({"contributed": False, "exclusion_reason": str(error)})
            return None, base

    items = list(selected.iterrows())
    if args.n_jobs == 1:
        processed = [process(item) for item in items]
    else:
        with ThreadPoolExecutor(max_workers=args.n_jobs) as executor:
            processed = list(executor.map(process, items))
    recordings = [spectrum for spectrum, _ in processed if spectrum is not None]
    recording_table = pd.DataFrame([row for _, row in processed])
    if not recordings:
        raise RuntimeError("no recording produced a valid raw PSD")

    site_spectra = aggregate_recordings_by_subject_and_site(
        recordings,
        window_seconds=args.window_seconds,
        recording_reduction=args.recording_reduction,
        site_reduction=args.site_reduction,
    )
    missing_sites = {str(site).lower() for site in args.datasets} - set(site_spectra)
    if missing_sites:
        raise RuntimeError(
            "no valid recording spectrum was available for: "
            + ", ".join(sorted(missing_sites))
        )
    metrics = compute_line_noise_metrics(site_spectra)
    review = make_review_table(metrics)
    metrics.to_csv(output_dir / "line_noise_peak_metrics_hup_ucla.csv", index=False)
    review.to_csv(output_dir / "line_noise_review_hup_ucla.csv", index=False)
    recording_table.to_csv(output_dir / "contributing_recordings_hup_ucla.csv", index=False)

    subject_rows = []
    for site, spectrum in sorted(site_spectra.items()):
        site_recordings = [recording for recording in recordings if recording.site == site]
        for participant_id in spectrum.participant_ids:
            subject_rows.append(
                {
                    "site": site,
                    "participant_id": participant_id,
                    "number_of_recordings": sum(
                        recording.participant_id == participant_id
                        for recording in site_recordings
                    ),
                    "contributed_to_site_equally": True,
                }
            )
    pd.DataFrame(subject_rows).to_csv(
        output_dir / "contributing_subjects_hup_ucla.csv", index=False
    )
    for site in HUP_UCLA_LINE_NOISE_DATASETS:
        if site in site_spectra:
            _plot_site_spectrum(site_spectra[site], output_dir / f"raw_spectrum_{site}.png")
    if set(HUP_UCLA_LINE_NOISE_DATASETS).issubset(site_spectra):
        _plot_comparison(
            site_spectra, output_dir / "raw_spectrum_hup_ucla_comparison.png"
        )
    _write_line_noise_html(
        output_dir / "raw_line_noise_qc_hup_ucla.html",
        args=args,
        site_spectra=site_spectra,
        metrics=metrics,
        review=review,
        recording_table=recording_table,
    )
    logging.info("Wrote raw line-noise QC outputs to %s", output_dir)


def main(argv: Sequence[str] | None = None) -> None:
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments and arguments[0] == "--legacy":
        if argv is not None:
            raise ValueError("programmatic legacy invocation is not supported")
        sys.argv.pop(1)
        legacy_main()
        return
    args = parse_line_noise_args(arguments)
    logging.basicConfig(
        level=getattr(logging, str(args.log_level).upper(), logging.INFO),
        format="%(asctime)s %(levelname)s %(message)s",
    )
    run_line_noise_qc(args)


if __name__ == "__main__":
    main()
